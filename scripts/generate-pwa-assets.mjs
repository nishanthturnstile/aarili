for (const [name, source] of [
  ["latin", "noto-sans/files/noto-sans-latin-400-normal.woff2"],
  ["tamil", "noto-sans-tamil/files/noto-sans-tamil-tamil-400-normal.woff2"],
])
  output.set(
    `apps/web/public/pwa/${name}.woff2`,
    await readFile(`packages/ui/node_modules/@fontsource/${source}`),
  );

function chunk(type, bytes) {
  const data = Buffer.concat([Buffer.from(type), bytes]);
  let crc = 0xffffffff;
  for (const byte of data) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++)
      crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
  }
  const header = Buffer.alloc(4);
  header.writeUInt32BE(bytes.length);
  const tail = Buffer.alloc(4);
  tail.writeUInt32BE((crc ^ 0xffffffff) >>> 0);
  return Buffer.concat([header, data, tail]);
}
function icon(size) {
  const background = Buffer.from(theme.primary.slice(1), "hex");
  const foreground = Buffer.from(token("primary-foreground").slice(1), "hex");
  const raw = Buffer.alloc(size * (size * 3 + 1));
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const u = x / size,
        v = y / size;
      // An A within the maskable safe circle (no new external artwork).
      const leg =
        v >= 0.27 &&
        v <= 0.73 &&
        Math.abs(Math.abs(u - 0.5) - (v - 0.27) * 0.43) < 0.025;
      const bar = v >= 0.55 && v <= 0.59 && u >= 0.365 && u <= 0.635;
      (leg || bar ? foreground : background).copy(
        raw,
        y * (size * 3 + 1) + 1 + x * 3,
      );
    }
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(size);
  header.writeUInt32BE(size, 4);
  header[8] = 8;
  header[9] = 2;
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk("IHDR", header),
    chunk("IDAT", deflateSync(raw)),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}
output.set("apps/web/public/pwa/icon-192.png", icon(192));
output.set("apps/web/public/pwa/icon-512.png", icon(512));
output.set("apps/web/public/pwa/maskable-512.png", icon(512));
for (const [path, data] of output) {
  const bytes = Buffer.from(data);
  if (process.argv.includes("--check")) {
    if (!(await readFile(path)).equals(bytes))
      throw new Error(`Stale generated PWA asset: ${path}`);
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, bytes);
  }
}
console.info(
  `PWA: ${output.size} canonical static assets ${process.argv.includes("--check") ? "checked" : "generated"}.`,
);
