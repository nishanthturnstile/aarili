export function formatPaymentPaise(
  value: number | string,
  locale: "en" | "ta",
) {
  const n = BigInt(value);
  return `₹${new Intl.NumberFormat(locale === "ta" ? "ta-IN" : "en-IN").format(n / 100n)}.${(n % 100n).toString().padStart(2, "0")}`;
}
