export function formatOrderPaise(
  paise: number | string | null,
  locale: "en" | "ta",
) {
  if (paise === null) return "—";
  const digits = String(paise).padStart(3, "0");
  return `₹${new Intl.NumberFormat(locale === "ta" ? "ta-IN" : "en-IN").format(BigInt(digits.slice(0, -2)))}.${digits.slice(-2)}`;
}
